"""Build the Book from one manifest: book/book.yaml -> cards, PNGs, reader data, BOOK.md blocks, contact sheet.

Usage (from docs/assets/infographics/):
  python3 kit/book_build.py             render changed cards, lint them, write everything below
  python3 kit/book_build.py --check     write nothing; exit 1 if anything is out of sync (CI)
  python3 kit/book_build.py --list      the Book in manifest order: number, id, title, status
  options: --force (render every card), --skip-lint (with --check: skip the render+lint pass, fast)

Reads    book/book.yaml and every card spec it lists (title and caption live in the spec only)
Writes   book/<folder>/<id>.png                      the card (only when its pixels change)
         public/infographics/book/<folder>/<id>.png  the copy the reader serves
         src/data/infographicBook.ts                 reader data, whole file, generated
         BOOK.md                                     only between `<!-- book:begin KEY -->` / `<!-- book:end KEY -->`
                                                     (KEY: toc, cards-<folder>); the prose around the markers is hand-written
         book/sheet.png                              contact sheet, manifest order
         book/book.lock.json                         what each PNG was built from (spec + script + renderer)
"Changed" = the card's spec or script, or the renderer (kit vocab/skins/render/spec + engine-v4), differs from the lock.
--check compares those fingerprints, not pixels, so it does not depend on the machine's Pillow version.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import tempfile
from collections import namedtuple

import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from kit import book_sync, lint, render, sheet, skins, spec as specmod  # noqa: E402

REPO = os.path.normpath(os.path.join(skins.INFOGRAPHICS, "..", "..", ".."))
Paths = namedtuple("Paths", "book public ts md")  # book = dir holding book.yaml, cards and sheet.png
DEFAULT = Paths(book=os.path.join(skins.INFOGRAPHICS, "book"),
                public=os.path.join(REPO, "public", "infographics", "book"),
                ts=book_sync.TS, md=book_sync.BOOK)
STATUSES = ("draft", "approved", "to-make")
SHEET_COLS = 6
GENERATED_NOTE = "generated by kit/book_build.py, edit book/book.yaml"
TOC_NEEDED = "toc"
UNPUBLISHED = ("adp/",)  # book/<folder>/ with specs + PNGs that are not in book.yaml yet (waits for Sasha's yes); not an orphan


# ------------------------------------------------------------------ manifest
class Card(dict):
    """id, status, folder, title, caption, image (path under book/), spec (Spec | None), placeholder."""


def _word(status):
    return str(status).split()[0] if status else ""


def load(paths=DEFAULT):
    """-> (title, chapters, errors). chapters: flat list in reading order of dicts
    {number, depth, title, note, toc, coming, cards}; a part's sections follow the part."""
    errors = []
    with open(os.path.join(paths.book, "book.yaml"), encoding="utf-8") as f:
        data = yaml.safe_load(f)
    chapters, seen_ids, seen_nums = [], set(), set()

    def chapter(node, depth, parent):
        num = str(node.get("number", ""))
        where = f"chapter {num or '?'}"
        if not num or not node.get("title"):
            errors.append(f"{where}: number and title are required")
        if num in seen_nums:
            errors.append(f"{where}: duplicate chapter number")
        seen_nums.add(num)
        if parent and not num.startswith(parent + "."):
            errors.append(f"{where}: a section of part {parent} must be numbered {parent}.N")
        status = node.get("status")
        coming = status is not None and _word(status) == "to-make"
        if status is not None and _word(status) not in STATUSES:
            errors.append(f"{where}: status {status!r} must start with one of {', '.join(STATUSES)}")
        cards = [_card(c, num, errors, seen_ids, paths) for c in node.get("cards") or []]
        if coming and cards:
            errors.append(f"{where}: status to-make but it lists cards")
        chapters.append(dict(number=num, depth=depth, title=node.get("title", ""), note=node.get("note"),
                             toc=node.get("toc"), coming=coming, cards=cards))
        for s in node.get("sections") or []:
            if depth == 2:
                errors.append(f"{where}: sections nest one level only")
            else:
                chapter(s, 2, num)

    for node in data.get("chapters") or []:
        chapter(node, 1, None)
    return data.get("title", ""), chapters, errors


def _card(entry, chapter_no, errors, seen_ids, paths):
    cid, status = str(entry.get("id", "")), entry.get("status", "")
    where = f"card {cid or '?'}"
    if not cid:
        errors.append("a card entry has no id")
    if cid in seen_ids:
        errors.append(f"{where}: listed twice")
    seen_ids.add(cid)
    if _word(status) not in STATUSES:
        errors.append(f"{where}: status {status!r} must start with one of {', '.join(STATUSES)}")
    placeholder = _word(status) == "to-make" and not entry.get("spec")
    card = Card(id=cid, status=str(status), placeholder=placeholder, spec=None, folder="", image="",
                title=entry.get("title", ""), caption=entry.get("caption", ""))
    if placeholder:
        if not card["title"]:
            errors.append(f"{where}: a to-make placeholder needs a title")
        return card
    rel = str(entry.get("spec", ""))
    path = os.path.join(paths.book, rel)
    if not rel.endswith(".card.yaml") or rel.count("/") != 1:
        errors.append(f"{where}: spec must be <folder>/<id>.card.yaml, got {rel!r}")
        return card
    if not os.path.exists(path):
        errors.append(f"{where}: spec file {rel} does not exist")
        return card
    spec = specmod.load(path)
    folder, stem = rel.split("/")[0], os.path.basename(rel)[: -len(".card.yaml")]
    if stem != cid:
        errors.append(f"{where}: spec file is named {stem}, the id must match")
    if spec.get("id") != cid:
        errors.append(f"{where}: spec says id {spec.get('id')!r}")
    if str(spec.get("chapter")) != chapter_no:
        errors.append(f"{where}: sits in chapter {chapter_no}, spec says chapter {spec.get('chapter')!r}")
    miss = specmod.missing(spec)
    if miss:
        errors.append(f"{where}: spec incomplete: {', '.join(miss)}")
    card.update(spec=spec, folder=folder, image=f"{folder}/{cid}.png", title=spec.get("title", ""),
                caption=spec.get("caption") or "")
    return card



def cards_of(chapters):
    return [c for ch in chapters for c in ch["cards"] if not c["placeholder"]]


# ------------------------------------------------------------------ generated text
TS_HEAD = '''/**
 * The Book of Psychoactive Infographics, as data for the reader at /game/learn/book (spec row C4).
 *
 * GENERATED by docs/assets/infographics/kit/book_build.py: do not edit this file.
 * Edit docs/assets/infographics/book/book.yaml (order, chapters, status) or a card's *.card.yaml
 * (title, caption), then run `python3 kit/book_build.py` from docs/assets/infographics/.
 * Nothing is parsed at runtime. Chapters are in manifest order. Card images live in
 * docs/assets/infographics/book/ (the source) and are copied to public/infographics/book/
 * with the same folder names (first-principles, ideal-client, laws, noosphere).
 *
 * The word "psychoactive" is the book's name only; it never appears on a card.
 */

export interface BookCard {
  /** Card id from BOOK.md (primitives-NN, ideal-client-NN, noosphere-N, or the law's old ID such as III.01). */
  id: string;
  title: string;
  /** The one-line caption from BOOK.md. Absent where BOOK.md has none. */
  caption?: string;
  /** Public URL of the card image. */
  image: string;
  /** Status as BOOK.md states it, e.g. "draft v4". */
  status: string;
}

export interface BookChapter {
  /** Number as in BOOK.md contents: "1", "2.1", "3.2". */
  number: string;
  title: string;
  /** 1 = a part of the book, 2 = a chapter inside a part. */
  depth: 1 | 2;
  /** The aside BOOK.md gives after the title, e.g. "the course's main infographic". */
  note?: string;
  /** True where BOOK.md says "(to make)" or lists no cards yet: shown as a quiet "coming" row. */
  coming: boolean;
  /** Cards in BOOK.md order. Empty for a coming chapter and for a part that only holds chapters. */
  cards: BookCard[];
}
'''

TS_TAIL = '''];

/** All cards of the book in reading order, for counting and checks. */
export const BOOK_CARDS: BookCard[] = BOOK_CHAPTERS.flatMap((c) => c.cards);
'''


def _j(s):
    return json.dumps(s, ensure_ascii=False)


def gen_ts(title, chapters):
    out = [TS_HEAD, f"\nexport const BOOK_TITLE = {_j(title)};\n\n", "export const BOOK_CHAPTERS: BookChapter[] = [\n"]
    for ch in chapters:
        out.append("  {\n")
        out.append(f"    number: {_j(ch['number'])},\n    title: {_j(ch['title'])},\n    depth: {ch['depth']},\n")
        if ch["note"]:
            out.append(f"    note: {_j(ch['note'])},\n")
        out.append(f"    coming: {'true' if ch['coming'] else 'false'},\n")
        cards = [c for c in ch["cards"] if not c["placeholder"]]
        if not cards:
            out.append("    cards: [],\n")
        else:
            out.append("    cards: [\n")
            for c in cards:
                cap = f" caption: {_j(c['caption'])}," if c["caption"] else ""
                out.append(f"      {{ id: {_j(c['id'])}, title: {_j(c['title'])},{cap} "
                           f"image: {_j('/infographics/book/' + c['image'])}, status: {_j(c['status'])} }},\n")
            out.append("    ],\n")
        out.append("  },\n")
    out.append(TS_TAIL)
    return "".join(out)


def gen_toc(chapters):
    lines = []
    for ch in chapters:
        own = [c for c in ch["cards"]]
        if ch["toc"] is not None:
            suffix = f" {ch['toc']}" if ch["toc"] else ""
        elif ch["coming"]:
            suffix = " (to make)"
        elif own:
            real = [c for c in own if not c["placeholder"]]
            suffix = f" ({len(real)} cards)" + (f" ({len(own) - len(real)} to make)" if len(own) > len(real) else "")
        else:
            suffix = ""
        note = f" ({ch['note']})" if ch["note"] else ""
        head = f"{ch['number']}. " if ch["depth"] == 1 else f"   - {ch['number']} "
        lines.append(f"{head}{ch['title']}{note}{suffix}")
    return "\n".join(lines)


def gen_cards_list(chapters, folder):
    lines = []
    for c in cards_of(chapters):
        if c["folder"] == folder:
            cap = f" · {c['caption']}" if c["caption"] else ""
            lines.append(f"- [{c['title']}](book/{c['image']}){cap} · status: {c['status']}")
    return "\n".join(lines)


MARK = re.compile(r"(?P<open><!-- book:begin (?P<key>[\w-]+)[^>]*-->\n)(?P<body>.*?)(?P<close><!-- book:end (?P=key) -->)", re.S)


def blocks_for(chapters):
    folders = sorted({c["folder"] for c in cards_of(chapters)})
    blocks = {TOC_NEEDED: gen_toc(chapters)}
    blocks.update({f"cards-{f}": gen_cards_list(chapters, f) for f in folders})
    return blocks


def apply_markers(md, blocks):
    """-> (new md, keys found). Replaces the body of every marker pair that has a generated block."""
    found = []

    def sub(m):
        key = m.group("key")
        found.append(key)
        if key not in blocks:
            return m.group(0)
        return m.group("open") + blocks[key] + "\n" + m.group("close")
    return MARK.sub(sub, md), found


def fingerprint_card(spec):
    h = hashlib.sha256()
    for p in (spec.path, spec.script):
        with open(p, "rb") as f:
            h.update(f.read())
        h.update(b"\0")
    return h.hexdigest()


def fingerprint_renderer():
    """Files that decide pixels: kit vocab/skins/render/spec, engine-v4 sources + fonts, the shared fonts."""
    kit = os.path.join(skins.INFOGRAPHICS, "kit")
    files = [os.path.join(kit, n) for n in ("vocab.py", "skins.py", "render.py", "spec.py", "__init__.py")]
    eng = skins.ENGINE
    files += [os.path.join(eng, n) for n in sorted(os.listdir(eng)) if n.endswith((".py", ".png"))]
    for d in {os.path.join(eng, "fonts"), skins.FONTS}:
        if os.path.isdir(d):
            files += [os.path.join(d, n) for n in sorted(os.listdir(d))]
    h = hashlib.sha256()
    for p in sorted(set(files)):
        h.update(os.path.relpath(p, skins.INFOGRAPHICS).encode()); h.update(b"\0")
        with open(p, "rb") as f:
            h.update(f.read())
    return h.hexdigest()


def fingerprint_sheet(cards, paths):
    h = hashlib.sha256()
    for c in cards:
        h.update(f"{c['id']}\0{c['title']}\0".encode())
        with open(os.path.join(paths.book, c["image"]), "rb") as f:
            h.update(f.read())
    return h.hexdigest()


def _sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def _lock_path(paths):
    return os.path.join(paths.book, "book.lock.json")


def read_lock(paths):
    p = _lock_path(paths)
    return json.loads(_read(p)) if os.path.exists(p) else {"renderer": "", "sheet": "", "cards": {}}


def write_lock(paths, lock):
    lock = dict(_generated=GENERATED_NOTE, **{k: lock[k] for k in ("renderer", "sheet", "cards")})
    _write(_lock_path(paths), json.dumps(lock, indent=1, sort_keys=True) + "\n")


def pixel_diff(a, b):
    import numpy as np
    from PIL import Image
    x, y = Image.open(a).convert("RGB"), Image.open(b).convert("RGB")
    if x.size != y.size:
        return None
    return float(np.abs(np.asarray(x, dtype=float) - np.asarray(y, dtype=float)).mean())


# ------------------------------------------------------------------ build
def render_card(card, paths, out_png):
    """Render to out_png, lint. -> list of FAIL lines (empty = lint PASS)."""
    spec = card["spec"]
    c = render.build(spec)
    c.save(out_png)
    return [f"FAIL  {card['id']}  {r:<11} {d}" for r, ok, d in lint.check(c, spec) if not ok]


def build(paths=DEFAULT, force=False, say=print):
    title, chapters, errors = load(paths)
    if errors:
        for e in errors:
            say(f"ERROR {e}")
        return 1
    cards = cards_of(chapters)
    lock = read_lock(paths)
    renderer = fingerprint_renderer()
    stale_all = force or lock.get("renderer") != renderer
    failed, rendered = 0, 0
    new_cards = dict(lock["cards"])
    with tempfile.TemporaryDirectory() as tmp:
        for c in cards:
            fp = fingerprint_card(c["spec"])
            dest = os.path.join(paths.book, c["image"])
            if not stale_all and lock["cards"].get(c["id"]) == fp and os.path.exists(dest):
                continue
            new = os.path.join(tmp, c["id"].replace(".", "_") + ".png")
            fails = render_card(c, paths, new)
            rendered += 1
            if fails:
                failed += 1
                for line in fails:
                    say(line)
                continue
            if os.path.exists(dest):
                d = pixel_diff(dest, new)
                if d == 0.0:
                    say(f"same     {c['image']}")
                else:
                    say(f"CHANGED  {c['image']}  mean abs pixel diff vs previous: {'size differs' if d is None else f'{d:.4f}'}")
                    shutil.copyfile(new, dest)
            else:
                say(f"NEW      {c['image']}")
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                shutil.copyfile(new, dest)
            new_cards[c["id"]] = fp
    say(f"rendered {rendered} of {len(cards)} card(s), {failed} failed lint")
    if failed:
        return 1
    for c in cards:  # public copies
        src, dst = os.path.join(paths.book, c["image"]), os.path.join(paths.public, c["image"])
        if not os.path.exists(dst) or _sha(src) != _sha(dst):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(src, dst)
            say(f"public   {c['image']}")
    wanted = {c["image"] for c in cards}
    for img in _pngs(paths.public):
        if img not in wanted:
            os.remove(os.path.join(paths.public, img))
            say(f"removed  public/{img} (not in book.yaml)")
    for img in _pngs(paths.book):
        if img not in wanted and img != "sheet.png" and not img.startswith(UNPUBLISHED):
            say(f"WARNING  book/{img} is not in book.yaml (kept; delete it or list it)")
    _write(paths.ts, gen_ts(title, chapters))
    md, found = apply_markers(_read(paths.md), blocks_for(chapters))
    _write(paths.md, md)
    if TOC_NEEDED not in found:
        say("ERROR    BOOK.md has no `<!-- book:begin toc -->` block")
        return 1
    sheet_fp = fingerprint_sheet(cards, paths)
    sheet_png = os.path.join(paths.book, "sheet.png")
    if force or lock.get("sheet") != sheet_fp or not os.path.exists(sheet_png):
        sheet.make_sheet([c["spec"] for c in cards], sheet_png, SHEET_COLS)
        say("sheet    book/sheet.png")
    write_lock(paths, dict(renderer=renderer, sheet=sheet_fp, cards={c["id"]: new_cards[c["id"]] for c in cards}))
    say("book_build: done")
    return 0


def _pngs(root):
    out = []
    for d, _, files in os.walk(root):
        out += [os.path.relpath(os.path.join(d, f), root).replace(os.sep, "/") for f in files if f.endswith(".png")]
    return sorted(out)


# ------------------------------------------------------------------ check
def check(paths=DEFAULT, skip_lint=False, say=print):
    title, chapters, errors = load(paths)
    bad = [f"manifest: {e}" for e in errors]
    if errors:
        return _report(bad, say)
    cards = cards_of(chapters)
    lock = read_lock(paths)
    if lock.get("renderer") != fingerprint_renderer():
        bad.append("renderer (kit vocab/skins/render/spec or engine-v4) changed since the PNGs were built: run kit/book_build.py")
    for c in cards:
        png = os.path.join(paths.book, c["image"])
        if not os.path.exists(png):
            bad.append(f"{c['id']}: book/{c['image']} is missing: run kit/book_build.py")
            continue
        if lock["cards"].get(c["id"]) != fingerprint_card(c["spec"]):
            bad.append(f"{c['id']}: spec or script changed, PNG not rebuilt: run kit/book_build.py")
        pub = os.path.join(paths.public, c["image"])
        if not os.path.exists(pub):
            bad.append(f"{c['id']}: public/infographics/book/{c['image']} is missing: run kit/book_build.py")
        elif _sha(pub) != _sha(png):
            bad.append(f"{c['id']}: public/infographics/book/{c['image']} differs from book/{c['image']}: run kit/book_build.py")
    wanted = {c["image"] for c in cards}
    for img in _pngs(paths.book):
        if img not in wanted and img != "sheet.png" and not img.startswith(UNPUBLISHED):
            bad.append(f"book/{img} is not in book.yaml")
    for img in _pngs(paths.public):
        if img not in wanted:
            bad.append(f"public/infographics/book/{img} is not in book.yaml")
    if not bad or all("PNG" not in b and "missing" not in b for b in bad):
        sheet_png = os.path.join(paths.book, "sheet.png")
        if not os.path.exists(sheet_png) or lock.get("sheet") != fingerprint_sheet(cards, paths):
            bad.append("book/sheet.png is missing or older than the cards: run kit/book_build.py")
    if not os.path.exists(paths.ts) or _read(paths.ts) != gen_ts(title, chapters):
        bad.append(f"{os.path.relpath(paths.ts, REPO)} is not what book.yaml generates: run kit/book_build.py")
    md = _read(paths.md)
    blocks = blocks_for(chapters)
    new_md, found = apply_markers(md, blocks)
    if new_md != md:
        bad.append("BOOK.md generated blocks are out of date: run kit/book_build.py")
    if TOC_NEEDED not in found:
        bad.append("BOOK.md has no `<!-- book:begin toc -->` block")
    book_ids, ts_ids = book_sync.parse_book(md), book_sync.parse_ts(_read(paths.ts)) if os.path.exists(paths.ts) else {}
    for c in cards:
        status, detail = book_sync.check_spec(c["spec"], book_ids, ts_ids)
        if status == "FAIL":
            bad.append(f"{c['id']}: book_sync: {detail}")
    if not skip_lint:
        with tempfile.TemporaryDirectory() as tmp:
            for c in cards:
                try:
                    bad += render_card(c, paths, os.path.join(tmp, "x.png"))
                except Exception as e:  # a script that no longer renders
                    bad.append(f"FAIL  {c['id']}  render {type(e).__name__}: {e}")
    return _report(bad, say, len(cards))


def _report(bad, say, n=0):
    for b in bad:
        say(f"FAIL {b}" if not b.startswith("FAIL") else b)
    say(f"book_build --check: {n} card(s), {len(bad)} problem(s)" if bad else f"book_build --check: {n} card(s), in sync, lint PASS")
    return 1 if bad else 0


def listing(paths=DEFAULT, say=print):
    _, chapters, errors = load(paths)
    for ch in chapters:
        say(f"{ch['number']:<4} {ch['title']}" + (" [to make]" if ch["coming"] else ""))
        for c in ch["cards"]:
            say(f"       {c['id']:<16} {c['title']}  [{c['status']}]")
    for e in errors:
        say(f"ERROR {e}")
    return 1 if errors else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true"); ap.add_argument("--list", action="store_true")
    ap.add_argument("--force", action="store_true"); ap.add_argument("--skip-lint", action="store_true")
    a = ap.parse_args()
    if a.list:
        sys.exit(listing())
    sys.exit(check(skip_lint=a.skip_lint) if a.check else build(force=a.force))
