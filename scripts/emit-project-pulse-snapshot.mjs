#!/usr/bin/env node
/**
 * Emits a JSON snapshot of the Project Pulse log for future dashboard/admin use.
 *
 * The canonical narrative ledger lives in `docs/09-logs/project_pulse_log.md`.
 * This script keeps the first implementation markdown-native while creating a
 * structured build-time surface the app can import later.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";

import { readBroadcastTracker } from "./sources/broadcast-tracker.mjs";
import { buildAnonymizer } from "./sources/anonymize.mjs";

const REPO_ROOT = join(import.meta.dirname, "..");
const LOG_PATH = join(REPO_ROOT, "docs", "09-logs", "project_pulse_log.md");
const OUT_PATH = join(REPO_ROOT, "src", "generated", "project-pulse-snapshot.json");
// Public copy so server-side readers (generate-pulse-brief edge function,
// equilibrium-telegram-bot edge function) can fetch the same snapshot over
// HTTP after deploy — both fetch `${SITE_ORIGIN}/generated/project-pulse-snapshot.json`
// at request time, so this file must exist in the deployed build. It is
// gitignored (regenerated by predev/prebuild, never committed) and its
// contents are anonymized below before either copy is written, since this
// path is an unauthenticated public URL and OUT_PATH ships inside the
// bundled JS — neither is a private surface.
const PUBLIC_OUT_PATH = join(REPO_ROOT, "public", "generated", "project-pulse-snapshot.json");

export function parseYamlBlock(block) {
  const event = {};
  const lines = block.split("\n");

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const match = line.match(/^(\s*)(?:-\s+)?([a-zA-Z0-9_]+):\s*(.*)$/);
    if (!match) continue;

    const [, indentation, key, rawValue] = match;
    const value = rawValue.trim();

    if (value === ">") {
      const parts = [];
      const baseIndent = indentation.length;
      while (i + 1 < lines.length) {
        const nextLine = lines[i + 1];
        const nextIndent = nextLine.match(/^\s*/)?.[0].length ?? 0;
        if (!nextLine.trim() || nextIndent <= baseIndent) break;
        parts.push(nextLine.trim());
        i++;
      }
      event[key] = parts.join(" ").replace(/\s+/g, " ").trim() || null;
      continue;
    }

    if (!value.length) {
      const list = [];
      while (i + 1 < lines.length && /^\s+-\s+/.test(lines[i + 1])) {
        list.push(lines[i + 1].replace(/^\s+-\s+/, "").trim());
        i++;
      }
      event[key] = list.length ? list : null;
      continue;
    }

    event[key] = value;
  }

  return event;
}

export function readPulseEvents(markdown) {
  const logSection = markdown.split(/^## Log\s*$/m)[1] ?? "";
  const yamlBlocks = [...logSection.matchAll(/```yaml\n([\s\S]*?)```/g)];

  return yamlBlocks
    .map((match) => parseYamlBlock(match[1]))
    .map((event) => ({
      ...event,
      title: event.title ?? event.pulse ?? null,
    }))
    .filter((event) => event.title || event.what_happened);
}

function main() {
  mkdirSync(dirname(OUT_PATH), { recursive: true });

  let payload;

  try {
    const markdown = existsSync(LOG_PATH) ? readFileSync(LOG_PATH, "utf8") : "";
    const events = readPulseEvents(markdown);

    // Build the anonymizer from the CRM tracker so the same person gets the
    // same token whether they're mentioned in the CRM offer ledger or in
    // pulse-log prose (e.g. "Sasha to send Gleb the Reflection Proposal...").
    // Also feed in the pulse log's own `who:` / `actors:` fields — some
    // contacts (e.g. a brand-new one) show up there before they ever reach
    // the CRM tracker's Master Table. Falls back to a no-op scrubber if the
    // tracker can't be read, so a missing/renamed private ledger degrades to
    // unscrubbed rather than crashing the build — but that fallback should
    // never be silent in practice; see docs/07-technology/deploy_pipeline.md.
    const extraIdentities = events.flatMap((event) =>
      [event.who, event.actors].flat().filter((v) => typeof v === "string"),
    );
    let anonymizer = { scrubDeep: (value) => value };
    try {
      anonymizer = buildAnonymizer(readBroadcastTracker(), extraIdentities);
    } catch {
      // CRM tracker unreadable (e.g. private-ledger submodule not checked
      // out in this environment) — proceed without it rather than fail
      // the whole snapshot build.
    }

    const scrubbedEvents = anonymizer.scrubDeep(events);

    payload = {
      generated_at: new Date().toISOString(),
      source: "docs/09-logs/project_pulse_log.md",
      eventsCount: scrubbedEvents.length,
      latestEvent: scrubbedEvents[scrubbedEvents.length - 1] ?? null,
      phaseShiftDistribution: scrubbedEvents.reduce((acc, event) => {
        const key = event.phase_shift_significance ?? "unknown";
        acc[key] = (acc[key] ?? 0) + 1;
        return acc;
      }, {}),
      openNextActions: scrubbedEvents
        .filter((event) => event.next_action)
        .map((event) => ({
          date: event.date ?? null,
          title: event.title ?? null,
          next_action: event.next_action,
        }))
        .slice(-10),
    };
  } catch (err) {
    payload = {
      generated_at: new Date().toISOString(),
      source: "docs/09-logs/project_pulse_log.md",
      error: err instanceof Error ? err.message : String(err),
      eventsCount: 0,
      latestEvent: null,
      phaseShiftDistribution: {},
      openNextActions: [],
    };
  }

  writeFileSync(OUT_PATH, JSON.stringify(payload, null, 2) + "\n");
  mkdirSync(dirname(PUBLIC_OUT_PATH), { recursive: true });
  writeFileSync(PUBLIC_OUT_PATH, JSON.stringify(payload, null, 2) + "\n");
  const suffix = payload.error ? ` (fallback: ${payload.error})` : "";
  console.log(`✓ wrote ${OUT_PATH}${suffix}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
