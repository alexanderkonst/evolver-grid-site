#!/usr/bin/env node
/**
 * Regenerate supabase/functions/your-ai-console/prompts.ts, the edge function's copy of the Console
 * prompt text. The function deploys from supabase/functions alone and cannot import from src/, so the
 * text is generated, never typed: AI OS v6.0 from system-prompts/v6.0/system-prompt.md, the button
 * prompts by bundling src/prompts/user/consolePhoenixPrompts.ts (which imports the reused prompts).
 * A vitest drift test (src/lib/console/__tests__/consoleServer.test.ts) fails if this file is stale.
 *
 *   node scripts/sync-console-prompts.mjs
 */
import { buildSync } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bundled = buildSync({
  entryPoints: [path.join(root, "src/prompts/user/consolePhoenixPrompts.ts")],
  bundle: true,
  format: "esm",
  write: false,
  platform: "neutral",
}).outputFiles[0].text;
const mod = await import(`data:text/javascript;base64,${Buffer.from(bundled).toString("base64")}`);
const aiOs = fs.readFileSync(path.join(root, "system-prompts/v6.0/system-prompt.md"), "utf-8");

const out = `// GENERATED by scripts/sync-console-prompts.mjs. Do not edit by hand.
// Sources: system-prompts/v6.0/system-prompt.md and src/prompts/user/consolePhoenixPrompts.ts.
// Spec: docs/specs/your-ai-console/console-v1.md

export const AI_OS_VERSION = "6.0";

export const AI_OS_PROMPT: string = ${JSON.stringify(aiOs)};

export const CONSOLE_PROMPTS: Record<string, string> = ${JSON.stringify(mod.CONSOLE_PROMPTS, null, 2)};
`;
fs.writeFileSync(path.join(root, "supabase/functions/your-ai-console/prompts.ts"), out);
console.log("wrote supabase/functions/your-ai-console/prompts.ts");
