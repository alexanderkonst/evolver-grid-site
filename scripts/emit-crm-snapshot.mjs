#!/usr/bin/env node
/**
 * Emits a JSON snapshot of the CRM state for the admin dashboard.
 *
 * The CRM lives in `docs/02-strategy/strategic_crm_outreach_tracker.md` (human-edited). The
 * parser at `scripts/sources/broadcast-tracker.mjs` turns it into structured
 * data. That parser is Node-only (uses fs). To expose it to the React
 * dashboard without reimplementing the parser in the UI layer (explicit hard
 * constraint in the Phase-1 brief), we generate a small JSON snapshot at
 * build time and commit a fresh copy.
 *
 * Wiring:
 *   - npm `prebuild` hook runs this before `vite build`
 *   - output lands at `src/generated/crm-snapshot.json`
 *   - `src/pages/admin/Dashboard.tsx` imports it statically
 *
 * If the parser fails for any reason, we still emit a well-formed file with
 * an `error` field so the dashboard can render gracefully.
 */

import { existsSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";

import { readBroadcastTracker } from "./sources/broadcast-tracker.mjs";
import { buildAnonymizer } from "./sources/anonymize.mjs";

const REPO_ROOT = join(import.meta.dirname, "..");
const OUT_PATH = join(REPO_ROOT, "src", "generated", "crm-snapshot.json");
// Small, anonymized, tracked projection used by the Offers Board at runtime.
// Unlike the full CRM snapshot, this file is safe to commit and remains
// available to GitHub raw fetches without requiring a frontend deployment.
const RUNTIME_OFFERS_OUT_PATH = join(REPO_ROOT, "src", "generated", "crm-offers-runtime.json");
// Public copy so server-side readers (generate-pulse-brief edge function,
// equilibrium-telegram-bot edge function) can fetch the same snapshot over
// HTTP after deploy. Both `OUT_PATH` and `PUBLIC_OUT_PATH` are gitignored —
// they are build-time artifacts regenerated by predev/prebuild, not
// committed source. Real contact names are scrubbed below (see
// scripts/sources/anonymize.mjs) before either copy is written, because
// `OUT_PATH` ships inside the bundled JS and `PUBLIC_OUT_PATH` sits at an
// unauthenticated public URL — neither is a private surface.
const PUBLIC_OUT_PATH = join(REPO_ROOT, "public", "generated", "crm-snapshot.json");

function canonicalOfferType(value) {
  const normalized = String(value ?? "").trim().toLowerCase();
  if (normalized.startsWith("paid")) return "paid";
  if (normalized.startsWith("free")) return "free";
  if (normalized.startsWith("partnership")) return "partnership";
  return null;
}

function canonicalOfferStatus(value) {
  const normalized = String(value ?? "").trim().toLowerCase();
  if (normalized === "paid" || normalized.includes("paid — delivered")) return "paid";
  if (normalized.includes("booked")) return "booked";
  if (
    normalized.startsWith("closed") ||
    normalized.startsWith("delivered") ||
    normalized.startsWith("completed") ||
    normalized.includes("soft-no")
  ) return "closed";
  if (
    normalized.includes("replied") ||
    normalized.includes("response received") ||
    normalized.includes("scope-session-held")
  ) return "replied";
  return "waiting";
}

function toRuntimeOffer(offer) {
  const offerType = canonicalOfferType(offer.offerType);
  if (!offerType || !/^\d{4}-\d{2}-\d{2}$/.test(offer.dateSent ?? "") || !offer.name) return null;
  return {
    ...offer,
    offerType,
    status: canonicalOfferStatus(offer.status),
    nextFollowupDate: /^\d{4}-\d{2}-\d{2}$/.test(offer.nextFollowupDate ?? "")
      ? offer.nextFollowupDate
      : "",
    notes: "",
  };
}

function main() {
  mkdirSync(dirname(OUT_PATH), { recursive: true });

  let payload;
  try {
    const data = readBroadcastTracker();
    // `data` doubles as the free-text scan source — this is what catches a
    // Cyrillic full name sitting in a notes/prose field rather than a
    // structured name column (see scripts/sources/anonymize.mjs).
    const anonymizer = buildAnonymizer(data, [], data);
    payload = {
      generated_at: new Date().toISOString(),
      version: data.version ?? null,
      contactsCount: (data.contacts ?? []).length,
      stageDistribution: data.stageDistribution ?? {},
      segmentDistribution: data.segmentDistribution ?? {},
      energyLeakCount: data.energyLeakCount ?? 0,
      cashReceivedUsd: data.cashReceivedUsd ?? null,
      revShareContractsUsd: data.revShareContractsUsd ?? null,
      // "Upcoming" must mean upcoming: the tracker table keeps delivered
      // events for the record (✅ / DELIVERED / strikethrough), but the
      // snapshot should not present them as future — AI consumers were
      // reporting April events as "upcoming" in July.
      // Names in `participants` / `notes` are anonymized below — this is a
      // generated artifact, not the private tracker itself.
      upcomingEvents: anonymizer.scrubDeep(
        (data.upcomingEvents ?? [])
          .filter((e) => !/✅|delivered|~~/i.test(`${e.event ?? ""} ${e.notes ?? ""}`))
          .slice(0, 5),
      ),
      openItemsCount: (data.openItems ?? []).filter((x) => !x.done).length,
      // `offers[].name` and `offers[].notes` carry real contact names in the
      // source tracker; anonymized here for the same reason as above.
      offers: anonymizer.scrubDeep(data.offers ?? []),
    };

    // Report, don't silently drop: anything that still looks like a
    // Cyrillic personal name after scrubbing gets surfaced so a human can
    // decide whether it needs a manual entry, not lost in the noise.
    const residualCyrillic = anonymizer.scanForResidualCyrillicNames(payload);
    if (residualCyrillic.length) {
      console.warn(
        `⚠ crm snapshot: ${residualCyrillic.length} Cyrillic token(s) survived scrubbing and could not be attributed to a known contact — review before shipping: ${residualCyrillic.join(", ")}`,
      );
    }
  } catch (err) {
    payload = {
      generated_at: new Date().toISOString(),
      error: err instanceof Error ? err.message : String(err),
      contactsCount: 0,
      stageDistribution: {},
      segmentDistribution: {},
      energyLeakCount: 0,
      cashReceivedUsd: null,
      revShareContractsUsd: null,
      upcomingEvents: [],
      openItemsCount: 0,
      offers: [],
    };
  }

  writeFileSync(OUT_PATH, JSON.stringify(payload, null, 2) + "\n");
  mkdirSync(dirname(PUBLIC_OUT_PATH), { recursive: true });
  writeFileSync(PUBLIC_OUT_PATH, JSON.stringify(payload, null, 2) + "\n");

  if (!payload.error || !existsSync(RUNTIME_OFFERS_OUT_PATH)) {
    const runtimeOffers = {
      generated_at: payload.generated_at,
      offers: (payload.offers ?? []).map(toRuntimeOffer).filter(Boolean),
    };
    writeFileSync(RUNTIME_OFFERS_OUT_PATH, JSON.stringify(runtimeOffers, null, 2) + "\n");
  } else {
    console.warn(`⚠ kept existing ${RUNTIME_OFFERS_OUT_PATH}; private CRM source is unavailable`);
  }

  const suffix = payload.error ? ` (fallback: ${payload.error})` : "";
  console.log(`✓ wrote ${OUT_PATH}${suffix}`);
}

main();
